/* A.B.C. : catalogue par établissement, sans dépendance externe. */
'use strict';
const ABC_CATALOGUE = { school: '', items: [], shared: false, loading: false, busy: false, choice: '', request: 0 };
const ABC_RUBRIQUES = { entree: 'Entrées', plat: 'Plats principaux', accomp: 'Accompagnements', dessert: 'Desserts & laitages' };
function abcCle(v) { return String(v || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/œ/g, 'oe').replace(/[^a-z0-9]+/g, ' ').trim(); }
function abcEcole() { return document.getElementById('select-etablissement')?.value || ''; }
function abcJour() { return new Intl.DateTimeFormat('fr-CA', {timeZone:'Europe/Paris',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date()); }
function abcEl(tag, texte, classe) { const e = document.createElement(tag); if (texte !== undefined) e.textContent = texte; if (classe) e.className = classe; return e; }
function abcMessage(texte) { const e=document.getElementById('abc-catalogue-status'); if(e) e.textContent=texte; }
function abcSelectionKey() { return 'abc-menu-v2-' + abcEcole() + '-' + (document.getElementById('input-menu-date')?.value || abcJour()); }
function abcSelection() { try { return JSON.parse(localStorage.getItem(abcSelectionKey()) || '[]'); } catch(e) { return []; } }
function abcSauverSelection() {
    const valeurs=Array.from(document.querySelectorAll('[data-catalogue-id]:checked')).map(e=>e.dataset.catalogueId+(e.dataset.maison ? ':maison' : ''));
    localStorage.setItem(abcSelectionKey(),JSON.stringify(valeurs));
}
function abcFicheFinale(item) {
    const vus=new Set();
    while(item?.fusionVers && !vus.has(item.id)) { vus.add(item.id); item=ABC_CATALOGUE.items.find(x=>x.id===item.fusionVers) || item; }
    return item;
}
function abcNomCatalogue(nom, composant) {
    if(ABC_CATALOGUE.school!==abcEcole()) return nom;
    const rubrique=composant==='accompagnement'?'accomp':composant;
    const cle=abcCle(nom);
    const candidats=ABC_CATALOGUE.items.filter(x=>(!rubrique || x.rubrique===rubrique) && [x.libelle,...(x.alias||[])].some(a=>abcCle(a)===cle)).map(abcFicheFinale);
    return candidats.length && candidats.every(x=>x.id===candidats[0].id) ? candidats[0].libelle : nom;
}
function abcAccepterCatalogue(data, school) {
    if(school!==abcEcole()) return;
    if(data.catalogueVersion===1 && Array.isArray(data.catalogue)) {
        const old=JSON.stringify(ABC_CATALOGUE.items);
        const locaux=ABC_CATALOGUE.items.filter(x=>x.local && !data.catalogue.some(y=>y.rubrique===x.rubrique && y.nature===x.nature && [y.libelle,...(y.alias||[])].some(n=>abcCle(n)===abcCle(x.libelle))));
        ABC_CATALOGUE.school=school; ABC_CATALOGUE.items=data.catalogue.concat(locaux); ABC_CATALOGUE.shared=true;
        abcMessage('Catalogue partagé de '+school+' · modifications enregistrées dans son Google Sheets.');
        if(old!==JSON.stringify(data.catalogue)) { abcAfficherCatalogue(); abcAfficherGestion(); }
    } else {
        abcMessage('Le catalogue partagé nécessite le nouveau GS. Les choix du menu sont utilisables ; les ajouts permanents seront disponibles après son installation.');
    }
    abcChoixMenu(data.historiqueMenus || {});
}
function abcChangerCatalogue() {
    ABC_CATALOGUE.school=abcEcole(); ABC_CATALOGUE.shared=false; ABC_CATALOGUE.choice=''; ABC_CATALOGUE.request++;
    ABC_CATALOGUE.items=ABC_CATALOGUE_INITIAL.map((x,i)=>({...x,id:'initial-'+i,alias:[],actif:true,revision:1,fusionVers:''}));
    // Les anciens favoris restent utilisables et peuvent être transférés explicitement.
    Object.keys(ABC_RUBRIQUES).forEach(type=>{
        let favoris=[];try{favoris=JSON.parse(localStorage.getItem('favs_'+abcEcole()+'_'+type)||'[]');}catch(e){}
        favoris.forEach((libelle,i)=>{if(!ABC_CATALOGUE.items.some(x=>x.rubrique===type&&abcCle(x.libelle)===abcCle(libelle))) ABC_CATALOGUE.items.push({id:'local-'+type+'-'+i,rubrique:type,nature:'base',libelle,alias:[],actif:true,revision:1,local:true});});
    });
    abcAfficherCatalogue(); abcAfficherGestion(); abcChoixMenu({});
    abcMessage('Chargement du catalogue de '+abcEcole()+'…');
}
async function abcRechargerCatalogue() {
    const school=abcEcole(),req=++ABC_CATALOGUE.request;
    abcMessage('Chargement du catalogue…');
    try {
        const r=await fetch(ADRESSE_SHEET_OFFICIELLE+'?action=getCatalogue&ecole='+encodeURIComponent(school)); const data=await r.json();
        if(req!==ABC_CATALOGUE.request || school!==abcEcole()) return;
        if(data.error) throw new Error(data.error);
        if(data.catalogueVersion!==1) throw new Error('Installez le nouveau GS pour activer le catalogue partagé.');
        abcAccepterCatalogue(data,school);
    } catch(e) { if(school===abcEcole()) abcMessage('Catalogue : '+e.message); }
}
async function abcModifierCatalogue(data) {
    if(!ABC_CATALOGUE.shared) throw new Error('Installez et redéployez le GS complet, puis cliquez sur « Recharger le catalogue ».');
    if(ABC_CATALOGUE.busy) throw new Error('Un enregistrement est déjà en cours.');
    const school=abcEcole();ABC_CATALOGUE.busy=true;abcMessage('Enregistrement dans le catalogue de '+school+'…');
    try {
        const r=await fetch(ADRESSE_SHEET_OFFICIELLE,{method:'POST',headers:{'Content-Type':'text/plain'},body:JSON.stringify({action:'saveCatalogue',ecole:school,...data})});
        const res=await r.json();
        if(!res.success || res.catalogueVersion!==1 || !Array.isArray(res.catalogue)) throw new Error(res.error || 'Le serveur ne confirme pas l’enregistrement du catalogue.');
        if(school===abcEcole()) abcAccepterCatalogue(res,school);
        return res;
    } finally { ABC_CATALOGUE.busy=false; }
}
function abcAfficherCatalogue() {
    const selected=new Set(abcSelection());
    document.querySelectorAll('[data-abc-rubrique]').forEach(td=>{
        const type=td.dataset.abcRubrique;td.replaceChildren();
        ['base','option'].forEach(nature=>{
            const titre=abcEl('div',nature==='base'?'Bases / Plats composés':'Options / Sauces / Préparations','sub-theme');td.append(titre);
            const groupe=abcEl('div');groupe.style.cssText='max-height:240px;overflow:auto;';td.append(groupe);
            ABC_CATALOGUE.items.filter(x=>x.rubrique===type&&x.nature===nature&&x.actif&&!x.fusionVers).forEach(x=>{
                const label=abcEl('label',undefined,'checkbox-label');const cb=abcEl('input');cb.type='checkbox';cb.dataset.catalogueId=x.id;
                cb.value=x.libelle;cb.name=type==='dessert'?'dessert_douceur':type+'_base';if(nature==='option')cb.name=type+'_opt';cb.checked=selected.has(x.id);
                cb.addEventListener('change',abcSauverSelection);label.append(cb,abcEl('span',(nature==='option'?'+ ':'')+x.libelle));
                if(nature==='base'){
                    const fm=abcEl('input');fm.type='checkbox';fm.name='fait_maison';fm.dataset.catalogueId=x.id;fm.dataset.maison='1';fm.checked=selected.has(x.id+':maison');fm.setAttribute('aria-label',x.libelle+' fait maison');fm.addEventListener('change',abcSauverSelection);
                    const span=abcEl('span');span.style.marginLeft='auto';span.append(fm,document.createTextNode(' 🧑‍🍳'));label.append(span);
                }
                groupe.append(label);
            });
            const ligne=abcEl('div');ligne.style.cssText='display:flex;gap:4px;margin:7px 0;';
            const input=abcEl('input');input.type='text';input.placeholder=nature==='base'?'Autre aliment…':'Autre sauce / option…';input.setAttribute('aria-label',ABC_RUBRIQUES[type]+' : '+input.placeholder);input.style.cssText='min-width:0;width:100%;padding:7px;border:1px solid #cbd5e1;border-radius:4px;';
            // Les anciens champs restent présents pour les fonctions de sauvegarde existantes.
            if(nature==='base')input.id=type+'_libre';
            const button=abcEl('button','💾');button.type='button';button.title='Enregistrer durablement dans le catalogue';button.setAttribute('aria-label','Enregistrer '+(nature==='base'?'l’aliment':'l’option'));button.style.cssText='padding:6px;border:1px solid #2d6a4f;border-radius:4px;background:#f0fdf4;';
            button.addEventListener('click',async()=>{
                const libelle=input.value.trim();if(!libelle)return;
                const school=abcEcole();button.disabled=true;
                try {const res=await abcModifierCatalogue({operation:'save',rubrique:type,nature,libelle});if(abcEcole()!==school)return;const sel=abcSelection();sel.push(res.id);localStorage.setItem(abcSelectionKey(),JSON.stringify(sel));abcAfficherCatalogue();}
                catch(e){abcMessage(e.message);}finally{button.disabled=false;}
            });ligne.append(input,button);td.append(ligne);
        });
    });
}
